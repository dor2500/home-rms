using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using HomeRms.Shared.Server;

namespace HomeRms.Controller.Services;

public enum InstallScope { Default, User, Machine }

/// <summary>The Install view's "Default Options" (apply to every app without a custom configuration).</summary>
public sealed record WingetScriptOptions(
    InstallScope Scope = InstallScope.Default,
    bool Interactive = false,
    bool Force = false,
    bool Silent = true,
    bool UpgradeIfInstalled = false);

/// <summary>
/// One app in a generated script. Null option values inherit <see cref="WingetScriptOptions"/>;
/// Override / Log / Location exist only per app ("Advanced Options").
/// </summary>
public sealed record WingetScriptApp(
    string Id,
    string? Version = null,
    InstallScope? Scope = null,
    bool? Interactive = null,
    bool? Force = null,
    string? Override = null,
    string? Log = null,
    string? Location = null);

/// <summary>
/// Builds the Install view's Batch / PowerShell / winget-import outputs (winstall's "Batch", "PowerShell"
/// and "Winget Import" tabs). IDs and versions are validated with <see cref="WingetRules"/>; free-text values
/// (--override / --log / --location) are quoted for the target shell and rejected when they cannot be
/// quoted safely (double quotes and control characters in batch files).
/// </summary>
public static class WingetScriptGenerator
{
    /// <summary>APPINSTALLER_CLI_ERROR_NO_APPLICATIONS_FOUND as a signed exit code (upgrade found nothing installed).</summary>
    public static readonly int NoPackageFoundExit = unchecked((int)WingetRules.NoPackageFound);

    private enum Shell { Batch, PowerShell }

    // ---------------- Single command (app page) ----------------
    /// <summary>winstall's app-page command: <c>winget install -e --id Google.Chrome</c> (plus <c>-v</c> when pinned).</summary>
    public static string SingleCommand(string id, string? version, bool upgrade)
    {
        Validate(id, version);
        var verb = upgrade ? "upgrade" : "install";
        return $"winget {verb} -e --id {id}{(string.IsNullOrEmpty(version) ? "" : $" -v {version}")}";
    }

    // ---------------- Batch ----------------
    public static string Batch(IReadOnlyList<WingetScriptApp> apps, WingetScriptOptions options)
    {
        var sb = new StringBuilder();
        sb.Append("@echo off\r\n");
        sb.Append($"REM Generated by Home RMS Deploy: {apps.Count} app(s). Requires Windows Package Manager (winget).\r\n");
        foreach (var app in apps)
        {
            var args = Arguments(app, options, Shell.Batch);
            if (options.UpgradeIfInstalled)
            {
                sb.Append($"winget upgrade {args}\r\n");
                sb.Append($"if %ERRORLEVEL% EQU {NoPackageFoundExit} winget install {args}\r\n");
            }
            else
            {
                sb.Append($"winget install {args}\r\n");
            }
        }
        return sb.ToString();
    }

    // ---------------- PowerShell ----------------
    public static string PowerShell(IReadOnlyList<WingetScriptApp> apps, WingetScriptOptions options)
    {
        var sb = new StringBuilder();
        sb.Append($"# Generated by Home RMS Deploy: {apps.Count} app(s). Requires Windows Package Manager (winget).\r\n");
        sb.Append("$ErrorActionPreference = 'Continue'\r\n");
        foreach (var app in apps)
        {
            var args = Arguments(app, options, Shell.PowerShell);
            if (options.UpgradeIfInstalled)
            {
                sb.Append($"winget upgrade {args}\r\n");
                sb.Append($"if ($LASTEXITCODE -eq {NoPackageFoundExit}) {{ winget install {args} }}\r\n");
            }
            else
            {
                sb.Append($"winget install {args}\r\n");
            }
        }
        return sb.ToString();
    }

    // ---------------- winget import ----------------
    /// <summary>A <c>winget import</c> file (winget-packages schema 2.0) with the pinned versions.</summary>
    public static string WingetImportJson(IReadOnlyList<WingetScriptApp> apps, DateTime? createdUtc = null)
    {
        var packages = new JsonArray();
        foreach (var app in apps)
        {
            Validate(app.Id, app.Version);
            var p = new JsonObject { ["PackageIdentifier"] = app.Id };
            if (!string.IsNullOrEmpty(app.Version)) p["Version"] = app.Version;
            packages.Add(p);
        }

        var root = new JsonObject
        {
            ["$schema"] = "https://aka.ms/winget-packages.schema.2.0.json",
            ["CreationDate"] = (createdUtc ?? DateTime.UtcNow).ToString("yyyy-MM-ddTHH:mm:ss.fffZ"),
            ["Sources"] = new JsonArray
            {
                new JsonObject
                {
                    ["Packages"] = packages,
                    ["SourceDetails"] = new JsonObject
                    {
                        ["Argument"] = "https://cdn.winget.microsoft.com/cache",
                        ["Identifier"] = "Microsoft.Winget.Source_8wekyb3d8bbwe",
                        ["Name"] = "winget",
                        ["Type"] = "Microsoft.PreIndexed.Package",
                    },
                },
            },
            ["WinGetVersion"] = "1.9",
        };
        return root.ToJsonString(new JsonSerializerOptions { WriteIndented = true });
    }

    // ---------------- Arguments ----------------
    private static string Arguments(WingetScriptApp app, WingetScriptOptions o, Shell shell)
    {
        Validate(app.Id, app.Version);
        var scope = app.Scope ?? o.Scope;
        var interactive = app.Interactive ?? o.Interactive;
        var force = app.Force ?? o.Force;

        var parts = new List<string> { $"--id={app.Id}", "-e" };
        if (!string.IsNullOrEmpty(app.Version)) parts.Add($"-v {app.Version}");
        if (scope != InstallScope.Default) parts.Add($"--scope {(scope == InstallScope.Machine ? "machine" : "user")}");
        if (interactive) parts.Add("--interactive");
        else if (o.Silent) parts.Add("--silent");
        if (force) parts.Add("--force");
        if (!string.IsNullOrWhiteSpace(app.Override)) parts.Add($"--override {Quote(app.Override, shell, "--override")}");
        if (!string.IsNullOrWhiteSpace(app.Log)) parts.Add($"--log {Quote(app.Log, shell, "--log")}");
        if (!string.IsNullOrWhiteSpace(app.Location)) parts.Add($"--location {Quote(app.Location, shell, "--location")}");
        if (o.Silent && !interactive) parts.Add("--accept-package-agreements --accept-source-agreements");
        return string.Join(' ', parts);
    }

    private static void Validate(string id, string? version)
    {
        if (!WingetRules.IsValidPackageId(id))
            throw new ArgumentException($"'{id}' is not a valid winget package id.");
        if (!string.IsNullOrEmpty(version) && !WingetRules.IsValidVersion(version))
            throw new ArgumentException($"'{version}' is not a valid version for {id}.");
    }

    /// <summary>True when <paramref name="value"/> can be written into a batch file (see <see cref="Quote"/>).</summary>
    public static bool IsBatchSafe(string? value) =>
        string.IsNullOrEmpty(value) || !value.Any(c => c == '"' || char.IsControl(c));

    private static string Quote(string value, Shell shell, string option)
    {
        value = value.Trim();
        if (value.Any(char.IsControl))
            throw new ArgumentException($"{option} must be a single line.");
        if (shell == Shell.PowerShell)
            return "'" + value.Replace("'", "''") + "'"; // single-quoted: no expansion of $ or backticks

        // Batch: inside double quotes & | < > ^ are literal; % must be doubled; a double quote cannot be embedded.
        if (value.Contains('"'))
            throw new ArgumentException($"{option} cannot contain double quotes in a batch file (use the PowerShell tab).");
        return "\"" + value.Replace("%", "%%") + "\"";
    }
}
